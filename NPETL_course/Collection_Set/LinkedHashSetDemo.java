import java.util.*;
public class LinkedHashSetDemo {
    public static void main(String[]args){
        LinkedHashSet<String> lhs = new LinkedHashSet<String>();

        //Add All the Elements
        lhs.add("A");
        lhs.add("B");
        lhs.add("C");
        lhs.add("D");
        lhs.add("E");
        lhs.add("F");
        System.out.println(lhs);

        //Same operation as hashset
    }
}
